// Generate a separate typed catalog from an explicitly selected compiler build.
import { readFile, writeFile, mkdir, realpath, lstat } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve, dirname, relative, isAbsolute } from "node:path";
import { fileURLToPath } from "node:url";
import { Interface } from "ethers";
import { contractDefinitions } from "./abi-types.mjs";

const sha = bytes => "sha256:" + createHash("sha256").update(bytes).digest("hex");
const object = x => x !== null && typeof x === "object" && !Array.isArray(x);
const own = (x, key) => object(x) && Object.hasOwn(x, key);
const forbidden = new Set(["__proto__", "constructor", "prototype"]);
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function renderBindings(buildBytes, targetBytes) {
  const build = JSON.parse(buildBytes), targets = JSON.parse(targetBytes);
  if (!object(build.input) || !object(build.output) || build.input.language !== "Solidity"
    || typeof build.solcVersion !== "string" || !/^0\.8\.19(?:\+|$)/.test(build.solcVersion))
    throw Error("Expected Solidity 0.8.19 compiler build-info with complete input and output");
  if (build.output.errors?.some(x => x.severity === "error")) throw Error("Compiler output contains errors");
  if (!object(targets) || !own(targets, "core")) throw Error("Targets must contain an explicit core binding");
  const abis = {}, selected = {};
  for (const key of Object.keys(targets).sort()) {
    if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) || forbidden.has(key)) throw Error(`Invalid binding name: ${key}`);
    const target = targets[key];
    if (!object(target) || Object.keys(target).sort().join(",") !== "contract,source"
      || typeof target.source !== "string" || typeof target.contract !== "string")
      throw Error(`Expected source and contract for ${key}`);
    const { source, contract } = target;
    if (!own(build.input.sources, source) || typeof build.input.sources[source].content !== "string")
      throw Error(`Missing literal compiler source: ${source}`);
    if (!own(build.output.contracts, source) || !own(build.output.contracts[source], contract))
      throw Error(`Missing compiled target: ${source}:${contract}`);
    const product = build.output.contracts[source][contract];
    if (!Array.isArray(product.abi) || product.abi.length === 0) throw Error(`Missing compiled ABI: ${key}`);
    const iface = new Interface(product.abi);
    if (iface.fragments.length !== product.abi.length) throw Error(`Unusable compiled ABI fragment: ${key}`);
    contractDefinitions({ [key]: product.abi });
    abis[key] = product.abi;
    selected[key] = { source, contract, sourceSha256: sha(build.input.sources[source].content),
      abiSha256: sha(JSON.stringify(product.abi)) };
  }
  const provenance = {
    schemaVersion: 1, source: "explicit-compiler-build-info",
    buildInfoSha256: sha(buildBytes), targetsSha256: sha(targetBytes),
    compilerVersion: build.solcLongVersion ?? build.solcVersion, targets: selected,
  };
  const header = "// Generated by Stream scripts/generate-bindings.mjs. Do not edit.\n";
  return {
    "abis.ts": header + `export const abis = ${JSON.stringify(abis, null, 2)} as const;\n`,
    "contracts.ts": header + `export type Hex = \`0x\${string}\`;\nexport type Address = Hex;\nexport interface ContractFunctions {\n${contractDefinitions(abis)}\n}\n`,
    "provenance.ts": header + `export const provenance = ${JSON.stringify(provenance, null, 2)} as const;\n`,
    "index.ts": header + `import type { Provider } from "ethers";
import { BoundStreamClient, boundStackConfigFromJSON, type BoundStackConfig } from "@6529/stream-client";
import { abis } from "./abis.js";
import type { ContractFunctions } from "./contracts.js";
export { abis } from "./abis.js";
export { provenance } from "./provenance.js";
export type { Address, Hex, ContractFunctions } from "./contracts.js";
export interface StackConfig extends BoundStackConfig<ContractFunctions> {}
export function stackConfigFromJSON(value: unknown): StackConfig {
  return boundStackConfigFromJSON<ContractFunctions>(value, abis);
}
export class StreamClient extends BoundStreamClient<ContractFunctions> {
  constructor(provider: Provider, config: StackConfig) { super(provider, config, abis); }
}
`,
  };
}

// Resolve an existing ancestor too, so an output symlink cannot select RC1 artifacts.
async function resolvedDestination(path) {
  try { return await realpath(path); } catch (error) {
    if (error.code !== "ENOENT") throw error;
    const parent = dirname(path);
    if (parent === path) throw error;
    return resolve(await resolvedDestination(parent), relative(parent, path));
  }
}
export async function generateBindings({ buildInfo, targets, out, check = false }) {
  const destination = await resolvedDestination(resolve(out));
  const protectedPaths = ["src/generated", "../../release-artifacts", "../../deployments"];
  for (const path of protectedPaths) {
    const protectedPath = await resolvedDestination(resolve(packageRoot, path));
    const rel = relative(protectedPath, destination);
    if (rel === "" || (!rel.startsWith("..") && !isAbsolute(rel))) throw Error("Output overlaps retained release/catalog paths");
  }
  const outputs = renderBindings(await readFile(buildInfo), await readFile(targets));
  for (const name of Object.keys(outputs)) {
    try {
      const stat = await lstat(resolve(destination, name));
      if (!stat.isFile() || stat.isSymbolicLink()) throw Error(`Output must be a regular file: ${name}`);
    } catch (error) { if (error.code !== "ENOENT") throw error; }
  }
  if (!check) await mkdir(destination, { recursive: true });
  for (const [name, content] of Object.entries(outputs)) {
    const file = resolve(destination, name);
    if (check) {
      let actual; try { actual = await readFile(file, "utf8"); } catch {}
      if (actual !== content) throw Error(`Stale compiler binding: ${name}`);
    } else await writeFile(file, content, "utf8");
  }
  return outputs;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const options = {}, args = process.argv.slice(2);
  for (let i = 0; i < args.length; i++) {
    const flag = args[i];
    if (flag === "--check" && options.check === undefined) { options.check = true; continue; }
    const key = new Map([["--build-info", "buildInfo"], ["--targets", "targets"], ["--out", "out"]]).get(flag);
    if (!key || options[key] !== undefined || !args[i + 1] || args[i + 1].startsWith("--"))
      throw Error("Usage: node scripts/generate-bindings.mjs --build-info FILE --targets FILE --out DIRECTORY [--check]");
    options[key] = args[++i];
  }
  if (!options.buildInfo || !options.targets || !options.out) throw Error("Explicit --build-info, --targets and --out are required");
  await generateBindings(options);
  console.log("Generated/verified typed bindings; deployment identity and signing domains require separate verification.");
}
